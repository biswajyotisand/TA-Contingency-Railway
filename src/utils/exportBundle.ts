import JSZip from 'jszip';
import { ProjectFile, FrameworkDetection } from '../types';

export interface ExportBundleOptions {
  files: Map<string, ProjectFile>;
  vercelJsonContent?: string;
  createExpressServerlessBridge?: boolean;
  serverEntryFile?: string;
  envVars?: Record<string, string>;
  generateRenderYaml?: boolean;
  generateDockerfile?: boolean;
  fixHardcodedLocalhost?: boolean;
}

export async function createDeployReadyZip(options: ExportBundleOptions): Promise<Blob> {
  const zip = new JSZip();

  // Copy existing files with potential transforms
  for (const [path, file] of options.files.entries()) {
    let content = file.content;

    // Apply auto-fix for hardcoded localhost if enabled
    if (options.fixHardcodedLocalhost && !file.isBinary) {
      if (path.endsWith('.js') || path.endsWith('.ts') || path.endsWith('.jsx') || path.endsWith('.tsx')) {
        content = content
          .replace(/https?:\/\/localhost:5000\/api/g, '/api')
          .replace(/https?:\/\/localhost:3000\/api/g, '/api')
          .replace(/https?:\/\/localhost:8000\/api/g, '/api')
          .replace(/https?:\/\/localhost:5000/g, '')
          .replace(/https?:\/\/localhost:3000/g, '');
      }
    }

    if (file.isBinary) {
      // Keep placeholder if binary
      zip.file(path, content);
    } else {
      zip.file(path, content);
    }
  }

  // 1. Add / update vercel.json
  if (options.vercelJsonContent) {
    zip.file('vercel.json', options.vercelJsonContent);
  }

  // 2. Add express serverless adapter if requested (e.g. api/index.js)
  if (options.createExpressServerlessBridge && options.serverEntryFile) {
    const relServerPath = options.serverEntryFile.replace(/\.(js|ts)$/, '');
    const bridgeContent = `// Vercel Serverless Function Bridge
// Automatically generated by CloudShip
const app = require('../${relServerPath}');

module.exports = app;
`;
    if (!options.files.has('api/index.js')) {
      zip.file('api/index.js', bridgeContent);
    }
  }

  // 3. Add .env.production.example or update .env.example
  if (options.envVars && Object.keys(options.envVars).length > 0) {
    const envLines = Object.entries(options.envVars)
      .map(([k, v]) => `${k}="${v}"`)
      .join('\n');
    zip.file('.env.example', envLines + '\n');
  }

  // 4. Ensure .gitignore has standard production excludes
  if (!options.files.has('.gitignore')) {
    const gitignoreContent = `# Dependencies
node_modules/
.pnp
.pnp.js

# Production build outputs
dist/
build/
.next/
out/
.output/

# Environment and secrets (NEVER commit to git!)
.env
.env.local
.env.development.local
.env.test.local
.env.production.local

# Logs and debug
npm-debug.log*
yarn-debug.log*
yarn-error.log*

# OS Files
.DS_Store
Thumbs.db
`;
    zip.file('.gitignore', gitignoreContent);
  }

  // 5. Optional Dockerfile for Render / Railway / Cloud Run
  if (options.generateDockerfile) {
    const dockerfile = `FROM node:20-alpine AS base

WORKDIR /app
COPY package*.json ./
RUN npm ci --omit=dev

COPY . .

# Build step if frontend build script exists
RUN npm run build --if-present

ENV NODE_ENV=production
ENV PORT=3000
EXPOSE 3000

CMD ["npm", "start"]
`;
    zip.file('Dockerfile', dockerfile);
  }

  // 6. Optional render.yaml for Render Blueprint
  if (options.generateRenderYaml) {
    const renderYaml = `services:
  - type: web
    name: fullstack-service
    runtime: node
    buildCommand: npm install && npm run build --if-present
    startCommand: npm start
    envVars:
      - key: NODE_ENV
        value: production
`;
    zip.file('render.yaml', renderYaml);
  }

  return await zip.generateAsync({ type: 'blob' });
}
